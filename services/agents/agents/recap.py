"""Halftime / full-time recap from verified moments and recorded events only.

build_recap is deterministic and always available: it ranks completed moments, keeps at most one per
possession, takes three, and writes a factual summary in which every number comes from team stats for
the scope. One tactical trend is named only when PPDA has at least two valid windows per team and the
difference is clear; otherwise the recap says the data is insufficient. Player focus uses recorded
on-ball events. Every substantive claim cites moment IDs.

narrate_recap optionally asks a model to rewrite headline and summary from the same facts packet; the
result is checked in code (numbers, names, score and meaning rules) and discarded if anything fails.
"""
from __future__ import annotations

import json
import re

from omnipitch_analytics.metrics import player_stats, ppda_series, team_stats

from .narrate import clock_label
from .semantics import BEHIND, DEFENDER_BREACH, LEAD, LEVEL, OUTSIDE_BOX, PASS_COUNT, SCORELINE, UNSUPPORTED_ADJECTIVE

RECAP_VERSION = "recap-v1"
SCOPES = ("first_half", "full_time")
RULE_WEIGHT = {"goal": 5, "chance": 4, "transition": 3, "pressing_change": 2, "threat_gain": 1}
TREND_RATIO = 1.25
NUMBER = re.compile(r"(?<![\w.])-?\d+(?:\.\d+)?")
LANGUAGES = ("en", "es")
LIMITATIONS = {
    "en": ["Synthetic match data generated by a seeded simulator.",
           "Built from recorded on-ball events and verified moments; no player tracking or off-ball work."],
    "es": ["Datos de partido sintéticos generados por un simulador con semilla.",
           "Basado en eventos con balón registrados y momentos verificados; sin seguimiento de jugadores ni trabajo sin balón."],
}


def _fmt(value: float) -> str:
    return f"{value:g}" if value == int(value) or abs(value) >= 10 else f"{value:.1f}".rstrip("0").rstrip(".")


def _possessive(name: str) -> str:
    return f"{name}'" if name.endswith("s") else f"{name}'s"


def _count(value: int, noun: str, plural: str | None = None) -> str:
    return f"{value} {noun}" if value == 1 else f"{value} {plural or noun + 's'}"


def _es_fmt(value: float) -> str:
    """Spanish decimal comma; same digits as _fmt so the checks on numbers still apply to the digits."""
    return _fmt(value).replace(".", ",")


def _strength(moment: dict) -> float:
    metrics = {m["name"]: m["value"] for m in moment["metrics"]}
    return metrics.get("forward_progress", 0) + 100 * metrics.get("threat_delta", 0) - metrics.get("shot_distance", 0)


def scope_events(events: list[dict], scope: str) -> list[dict]:
    return [e for e in events if scope == "full_time" or e["period"] == 1]


def build_recap(events: list[dict], moments: list[dict], scope: str, context: dict, home: str, away: str,
                language: str = "en") -> dict | None:
    """events: the revealed prefix; moments: verified moments with insights (and replay_ms when known).

    language "es" writes the same template in Spanish from the same numbers; names, scores and units are kept."""
    if scope not in SCOPES:
        raise ValueError(f"scope must be one of {SCOPES}")
    if language not in LANGUAGES:
        raise ValueError(f"language must be one of {LANGUAGES}")
    es = language == "es"
    in_scope = scope_events(events, scope)
    if not in_scope or (scope == "full_time" and not any(e["period"] == 2 for e in events)):
        return None
    run_id, match_id = in_scope[0]["run_id"], in_scope[0]["match_id"]
    final_period = 1 if scope == "first_half" else 2
    final = any(e["type"] == "period_end" and e["period"] == final_period for e in in_scope)
    last = in_scope[-1]
    through = last["sequence"]
    teams, players = context["teams"], context["players"]
    stats = {team: team_stats(in_scope, team) for team in (home, away)}
    attempts = sum(stats[team]["passes_attempted"] for team in (home, away))
    for team in (home, away):  # Share of both teams' pass attempts, as in the team comparison.
        stats[team]["pass_share_pct"] = round(100 * stats[team]["passes_attempted"] / attempts, 1) if attempts else None
    score = {"home": stats[home]["goals"], "away": stats[away]["goals"]}
    story = match_story(in_scope, scope, home, away)

    # Key moments: strongest verified moments, one per possession, then shown in match order.
    possession = {e["event_id"]: e.get("possession_id") for e in in_scope}
    candidates = [m for m in moments if m["source_sequence"] <= through and (scope == "full_time" or m["period"] == 1)]
    ranked = sorted(candidates, key=lambda m: (RULE_WEIGHT[m["rule"]], m["priority"], _strength(m)), reverse=True)
    chosen, seen = [], set()
    for moment in ranked:
        key = possession.get(moment["evidence_ids"][0]) or moment["moment_id"]
        if key in seen:
            continue
        seen.add(key)
        chosen.append(moment)
        if len(chosen) == 3:
            break
    chosen.sort(key=lambda m: (m["period"], m["match_time_ms"]))
    key_moments = [{"moment_id": m["moment_id"], "rule": m["rule"], "clock": clock_label(m["period"], m["match_time_ms"]),
                    "team_id": m.get("team_id"), "headline": m["insight"]["headline"],
                    "generation_mode": m["insight"]["generation_mode"], "source_sequence": m["source_sequence"],
                    "replay_ms": m.get("replay_ms", 0)} for m in chosen]

    clock = clock_label(last['period'], last['match_time_ms'])
    h, a = stats[home], stats[away]
    leader = home if score["home"] > score["away"] else away if score["away"] > score["home"] else None
    hi_lo = f"{max(score.values())}-{min(score.values())}"
    headline, summary = _story_text(story, score, h, a, teams, players, home, away, leader, hi_lo, scope, final, clock, es)

    # Tactical trend: one supported claim or an explicit insufficient-data message.
    windows = [w for w in ppda_series(in_scope, [home, away]) if w["closed"] and w["status"] == "ok"]
    per_team = {t: [w["value"] for w in windows if w["team_id"] == t] for t in (home, away)}
    if all(len(v) >= 2 for v in per_team.values()):
        mean = {t: round(sum(v) / len(v), 2) for t, v in per_team.items()}
        hi, lo = sorted((home, away), key=lambda t: mean[t])
        n_hi, n_lo = len(per_team[hi]), len(per_team[lo])
        if mean[lo] >= mean[hi] * TREND_RATIO:
            # PPDA states how many passes a team allowed per defensive action; it never proves where or whether a press worked.
            text = (f"{teams[hi]} permitió menos pases rivales por acción defensiva: PPDA medio {_es_fmt(mean[hi])} en {n_hi} ventanas "
                    f"válidas frente a {_es_fmt(mean[lo])} de {teams[lo]} ({n_lo}). El PPDA describe intensidad; no demuestra "
                    f"que la presión recuperara el balón.") if es else (
                    f"{teams[hi]} allowed fewer opponent passes per defensive action: mean PPDA {_fmt(mean[hi])} over {n_hi} "
                    f"valid windows against {_fmt(mean[lo])} for {teams[lo]} ({n_lo}). PPDA describes intensity; it does not "
                    f"show where the pressure happened or that it won the ball.")
            trend = {"supported": True, "metric": "ppda", "text": text,
                     "values": {"mean_ppda": {hi: mean[hi], lo: mean[lo]}, "valid_windows": {t: len(v) for t, v in per_team.items()}}}
        else:
            text = (f"Sin diferencia clara en el PPDA: media {_es_fmt(mean[home])} para {teams[home]} y {_es_fmt(mean[away])} "
                    f"para {teams[away]}.") if es else (
                    f"No clear PPDA difference: mean {_fmt(mean[home])} for {teams[home]} and {_fmt(mean[away])} for {teams[away]}.")
            trend = {"supported": True, "metric": "ppda", "text": text,
                     "values": {"mean_ppda": mean, "valid_windows": {t: len(v) for t, v in per_team.items()}}}
    else:
        trend = {"supported": False, "metric": None, "values": None,
                 "text": ("No hay suficientes ventanas de presión válidas para señalar una tendencia (se necesitan al menos dos "
                          "por equipo).") if es else
                         "Not enough valid pressing windows to name a tactical trend (needs at least two per team)."}

    # Player focus: recorded on-ball contribution only.
    rows = [r for r in player_stats(in_scope) if r["team_id"] in (home, away)]
    focus = None
    if rows:
        best = max(rows, key=lambda r: (r["goals"], r["threat_gained"], r["progression_m"]))
        name = players.get(best["player_id"], best["player_id"])
        text = (f"{name} ({teams[best['team_id']]}): {_count(best['passes_completed'], 'pase completado', 'pases completados')}, "
                f"{_es_fmt(best['progression_m'])} m de progreso hacia delante, {_count(best['shots'], 'tiro')}"
                + (f", {_count(best['goals'], 'gol', 'goles')}." if best["goals"] else ".")) if es else (
                f"{name} ({teams[best['team_id']]}): {_count(best['passes_completed'], 'completed pass', 'completed passes')}, "
                f"{_fmt(best['progression_m'])} m of forward progress, {_count(best['shots'], 'shot')}"
                + (f", {_count(best['goals'], 'goal')}." if best["goals"] else "."))
        focus = {"player_id": best["player_id"], "name": name, "team_id": best["team_id"], "text": text,
                 "metrics": [{"name": "passes_completed", "value": best["passes_completed"], "unit": "passes"},
                             {"name": "progression", "value": best["progression_m"], "unit": "m"},
                             {"name": "shots", "value": best["shots"], "unit": "shots"},
                             {"name": "goals", "value": best["goals"], "unit": "goals"}]}
    return {"schema_version": "1.1", "run_id": run_id, "match_id": match_id, "scope": scope,
            "status": "final" if final else "provisional", "through_sequence": through,
            "clock": clock_label(last["period"], last["match_time_ms"]), "score": score,
            "headline": headline, "summary": summary, "key_moments": key_moments, "tactical_trend": trend,
            "player_focus": focus, "sources": [k["moment_id"] for k in key_moments],
            "generation_mode": "fallback", "limitations": list(LIMITATIONS[language]), "recap_version": RECAP_VERSION,
            "language": language, "stats": {side: _comparable(stats[team]) for side, team in (("home", home), ("away", away))},
            "story": story}


def match_story(in_scope: list[dict], scope: str, home: str, away: str) -> dict:
    """The facts a recap is built around, from the recap's own events only: every goal with the score after it,
    whether the eventual leader ever trailed, the goal that decided it, and shots per half (full time)."""
    score, goals, trailed = {home: 0, away: 0}, [], {home: False, away: False}
    for event in in_scope:
        if event["type"] == "shot" and event.get("is_goal") and event.get("team_id") in score:
            score[event["team_id"]] += 1
            goals.append({"team_id": event["team_id"], "player_id": event.get("player_id"), "period": event["period"],
                          "clock": clock_label(event["period"], event["match_time_ms"]), "sequence": event["sequence"],
                          "score": {"home": score[home], "away": score[away]}})
            for team, other in ((home, away), (away, home)):
                trailed[team] = trailed[team] or score[team] < score[other]
    leader = home if score[home] > score[away] else away if score[away] > score[home] else None
    decisive = None
    if leader:  # The goal after which the leader was ahead for good.
        for goal in reversed(goals):
            ahead = goal["score"]["home" if leader == home else "away"] > goal["score"]["away" if leader == home else "home"]
            if not ahead:
                break
            decisive = goal
    elif goals:
        decisive = goals[-1]  # A draw: the last goal (the equaliser).
    halves = None
    if scope == "full_time":
        shots = {p: {t: sum(1 for e in in_scope if e["period"] == p and e["type"] == "shot" and e.get("team_id") == t) for t in (home, away)}
                 for p in (1, 2)}
        halves = {"first": {"home": shots[1][home], "away": shots[1][away]}, "second": {"home": shots[2][home], "away": shots[2][away]}}
    return {"goals": goals, "leader": leader, "came_from_behind": bool(leader and trailed[leader]),
            "decisive_goal": decisive, "shots_by_half": halves}


def _swing(halves: dict | None) -> str | None:
    """Which side the shots swung to after the break, when the change is large enough to be the story."""
    if not halves:
        return None
    first, second = halves["first"], halves["second"]
    if sum(first.values()) < 4 or sum(second.values()) < 6:
        return None
    share = lambda half: half["home"] / max(1, half["home"] + half["away"])
    change = share(second) - share(first)
    return "home" if change >= .25 and second["home"] > second["away"] else "away" if change <= -.25 and second["away"] > second["home"] else None


def _story_text(story: dict, score: dict, h: dict, a: dict, teams: dict, players: dict, home: str, away: str,
                leader: str | None, hi_lo: str, scope: str, final: bool, clock: str, es: bool) -> tuple[str, str]:
    """Outcome, turning point, supporting comparison and scorers, in that order; every number comes from the story."""
    name = lambda pid: players.get(pid or "", "")
    side = {home: "home", away: "away"}
    other = {home: away, away: home}
    scorers = []
    for team in (home, away):
        mine = [f"{name(g['player_id'])} {g['clock']}" for g in story["goals"] if g["team_id"] == team]
        if mine:
            joined = mine[0] if len(mine) == 1 else f"{', '.join(mine[:-1])} {'y' if es else 'and'} {mine[-1]}"
            scorers.append(f"{joined} {'para' if es else 'for'} {teams[team]}")
    decisive = story["decisive_goal"]
    swing = _swing(story["shots_by_half"])
    if es:
        when = ("al descanso" if scope == "first_half" else "al final") if final else f"tras el {clock} (provisional)"
        if not final:
            outcome = f"{teams[home]} {score['home']}, {teams[away]} {score['away']} {when}."
        elif leader and scope == "full_time":
            outcome = (f"{teams[leader]} remontó para ganar a {teams[other[leader]]} {hi_lo}." if story["came_from_behind"]
                       else f"{teams[leader]} ganó a {teams[other[leader]]} {hi_lo}.")
        elif leader:
            outcome = f"{teams[leader]} se va al descanso por delante, {hi_lo}."
        else:
            outcome = f"{teams[home]} y {teams[away]} empatan {score['home']}-{score['away']} {when}."
        turning = ""
        if final and decisive and leader and scope == "full_time" and len(story["goals"]) > 1:
            turning = f" El gol decisivo llegó en el {decisive['clock']}, de {name(decisive['player_id'])}."
        elif final and decisive and not leader and story["goals"]:
            turning = f" {teams[decisive['team_id']]} empató en el {decisive['clock']} con gol de {name(decisive['player_id'])}."
        if swing:
            t, o = (home, away) if swing == "home" else (away, home)
            first, second = story["shots_by_half"]["first"], story["shots_by_half"]["second"]
            comparison = (f" Tras el descanso, {teams[t]} disparó {second[side[t]]} veces por {second[side[o]]} de {teams[o]}, "
                          f"después de una primera parte de {first[side[t]]} a {first[side[o]]}.")
        else:
            comparison = (f" {teams[home]} sumó {_count(h['shots'], 'tiro')} ({h['shots_on_target']} a puerta) frente a "
                          f"{a['shots']} ({a['shots_on_target']}) de {teams[away]}.")
        goals_text = f" Goles: {'; '.join(scorers)}." if scorers else ""
        headline = (f"{teams[leader]} va ganando {hi_lo}" if leader and not final
                    else f"{teams[leader]} remonta y gana {hi_lo}" if leader and scope == "full_time" and story["came_from_behind"]
                    else f"{teams[leader]} gana {hi_lo}" if leader and scope == "full_time"
                    else f"{teams[leader]} gana {hi_lo} al descanso" if leader
                    else f"Termina en empate {score['home']}-{score['away']}" if final and scope == "full_time"
                    else f"Empate {score['home']}-{score['away']}")
    else:
        when = ("at half-time" if scope == "first_half" else "at full-time") if final else f"after {clock} (provisional)"
        if not final:
            outcome = f"{teams[home]} {score['home']}, {teams[away]} {score['away']} {when}."
        elif leader and scope == "full_time":
            outcome = (f"{teams[leader]} came from behind to beat {teams[other[leader]]} {hi_lo}." if story["came_from_behind"]
                       else f"{teams[leader]} beat {teams[other[leader]]} {hi_lo}.")
        elif leader:
            outcome = f"{teams[leader]} lead {hi_lo} at half-time."
        else:
            outcome = f"{teams[home]} and {teams[away]} are level at {score['home']}-{score['away']} {when}."
        turning = ""
        if final and decisive and leader and scope == "full_time" and len(story["goals"]) > 1:
            turning = f" The winning goal came at {decisive['clock']} from {name(decisive['player_id'])}."
        elif final and decisive and not leader and story["goals"]:
            turning = f" {teams[decisive['team_id']]} equalised at {decisive['clock']} through {name(decisive['player_id'])}."
        if swing:
            t, o = (home, away) if swing == "home" else (away, home)
            first, second = story["shots_by_half"]["first"], story["shots_by_half"]["second"]
            comparison = (f" After the break {teams[t]} had {second[side[t]]} shots to {second[side[o]]}, "
                          f"having been out-shot {first[side[o]]} to {first[side[t]]} in the first half.")
        else:
            comparison = (f" {teams[home]} had {_count(h['shots'], 'shot')} ({h['shots_on_target']} on target) to {_possessive(teams[away])} "
                          f"{a['shots']} ({a['shots_on_target']}).")
        goals_text = f" Scorers: {'; '.join(scorers)}." if scorers else ""
        headline = (f"{teams[leader]} lead {hi_lo}" if leader and not final
                    else f"{teams[leader]} come from behind to win {hi_lo}" if leader and scope == "full_time" and story["came_from_behind"]
                    else f"{teams[leader]} win {hi_lo}" if leader and scope == "full_time"
                    else f"{teams[leader]} lead {hi_lo} at the break" if leader
                    else f"Ends level at {score['home']}-{score['away']}" if final and scope == "full_time"
                    else f"Level at {score['home']}-{score['away']}")
    return headline, f"{outcome}{turning}{comparison}{goals_text}"


def _story_facts(story: dict | None, context: dict) -> dict | None:
    if not story:
        return None
    teams, players = context["teams"], context["players"]
    return {"goals": [{"team": teams[g["team_id"]], "scorer": players.get(g["player_id"] or "", ""), "clock": g["clock"],
                       "score_after": f"{g['score']['home']}-{g['score']['away']}"} for g in story["goals"]],
            "came_from_behind": story["came_from_behind"], "shots_by_half": story["shots_by_half"]}


def _comparable(stats: dict) -> dict:
    """Team numbers at the recap's own cutoff, for side-by-side rows (never from later events)."""
    return {key: stats[key] for key in ("goals", "shots", "shots_on_target", "box_entries", "final_third_entries",
                                        "progression_m", "completion_pct", "pass_share_pct", "turnovers_won")}


# Optional AI rewrite ---------------------------------------------------------------------------

def recap_facts(recap: dict, context: dict, home: str, away: str) -> dict:
    """The only material a model may see for a recap rewrite."""
    return {"scope": recap["scope"], "status": recap["status"], "clock": recap["clock"],
            "score": {context["teams"][home]: recap["score"]["home"], context["teams"][away]: recap["score"]["away"]},
            "summary_facts": recap["summary"], "key_moments": [{k: m[k] for k in ("clock", "rule", "headline")} for m in recap["key_moments"]],
            "tactical_trend": recap["tactical_trend"]["text"], "player_focus": (recap["player_focus"] or {}).get("text"),
            "story": _story_facts(recap.get("story"), context), "synthetic": True}


def validate_recap_text(headline: str, summary: str, recap: dict, context: dict, home: str, away: str) -> list[str]:
    errors: list[str] = []
    if not headline.strip() or len(headline) > 90:
        errors.append("headline must be 1-90 characters")
    if not summary.strip() or len(summary) > 600:
        errors.append("summary must be 1-600 characters")
    # Spanish text uses a decimal comma; compare the digits with the facts' decimal point.
    text = re.sub(r"(\d),(\d)", r"\1.\2", f"{headline} {summary}")
    source = re.sub(r"(\d),(\d)", r"\1.\2", json.dumps(recap_facts(recap, context, home, away), ensure_ascii=False))
    allowed = set(NUMBER.findall(source))
    for number in NUMBER.findall(text.replace("'", " ")):
        if number not in allowed:
            errors.append(f"unsupported number {number!r}")
    for player_id, name in context["players"].items():
        if name in text and name not in source:
            errors.append(f"player {name!r} is not in the recap facts")
    for pattern, reason in ((DEFENDER_BREACH, "defender-breach claim"), (OUTSIDE_BOX, "box position claim"),
                            (PASS_COUNT, "pass count claim")):
        # A pass count is allowed only when it is the recorded completed-pass count in the player focus.
        recorded = {f"{m['value']:g}" for m in (recap.get("player_focus") or {}).get("metrics", []) if m["name"] == "passes_completed"}
        if any(not (pattern is PASS_COUNT and set(re.findall(r"\d+", match.group(0))) <= recorded and re.search(r"\d", match.group(0)))
               for match in pattern.finditer(text)):
            errors.append(f"unsupported claim: {reason}")
    h, a = recap["score"]["home"], recap["score"]["away"]
    for x, y in SCORELINE.findall(text):
        if sorted((int(x), int(y))) != sorted((h, a)):
            errors.append(f"scoreline {x}-{y} contradicts the recap score {h}-{a}")
    if LEVEL.search(text) and h != a:
        errors.append("level claimed while one team leads")
    if (LEAD.search(text) or BEHIND.search(text)) and h == a:
        errors.append("lead claimed while the score is level")
    if re.search(r"\b(probabilit|xg\b|expected goals|caused|forced (a |the )?turnover)", text, re.I):
        errors.append("unsupported claim: probability or causation")
    if match := UNSUPPORTED_ADJECTIVE.search(text):
        errors.append(f"unsupported judgement: '{match.group(0)}' is not measured by this data")
    if recap.get("language") == "es":
        from .narrate_es import SPANISH_FORBIDDEN
        errors += [f"unsupported claim: {reason}" for pattern, reason in SPANISH_FORBIDDEN if pattern.search(text)]
    return errors


def narrate_recap(recap: dict, context: dict, home: str, away: str, client, timeout: float = 25.0) -> tuple[dict, str | None]:
    """Return (recap, reason). On any failure the deterministic recap is returned with the reason."""
    from .model import ModelError
    spanish = recap.get("language") == "es"
    messages = [
        {"role": "system", "content": (
            ("Write in natural Spanish (Spain), with a decimal comma. " if spanish else "")
            + "You write a short recap of a synthetic football match period for fans. Use only the supplied facts. "
            "Reuse numbers exactly as written; never compute new ones. Do not name players or events that are not in "
            "the facts. No player tracking exists: no speed, distance covered, positions, defenders beaten or "
            "'outside the box'. Do not count passes. Report, do not judge: no evaluative words such as dominant, dominated, "
            "brilliant, superb, clinical, impressive or deserved (in Spanish: dominante, dominó, brillante, espectacular). Return JSON {\"headline\": <=90 chars, \"summary\": <=600 chars}.")},
        {"role": "user", "content": json.dumps(recap_facts(recap, context, home, away))}]
    try:
        out = client.complete("recap", messages, timeout)
    except ModelError as exc:
        return recap, f"model error ({getattr(client, 'name', 'model')}): {str(exc)[:120]}"
    headline, summary = str(out.get("headline", "")).strip(), str(out.get("summary", "")).strip()
    errors = validate_recap_text(headline, summary, recap, context, home, away)
    if errors:
        return recap, f"AI recap failed validation: {errors[0]}"
    note = ("Redactado por IA a partir de los datos del resumen; cifras, nombres y marcador comprobados." if spanish
            else "AI-written from the recap facts; numbers, names and score were checked.")
    return {**recap, "headline": headline, "summary": summary, "generation_mode": "ai", "limitations": recap["limitations"] + [note]}, None
