"""Rule-based moment detection over an ordered event prefix.

Every rule is prefix-stable: a moment found after N events is found again, with identical
evidence, after N + k events. That lets callers re-run detection on each update and insert
new moments idempotently by moment_id.
"""
from __future__ import annotations

from .metrics import (METRIC_VERSION, PPDA_WINDOW_MS, box_entry, final_third_entry, forward_progress_m,
                      pass_distance_m, ppda_series, shot_distance_m, threat_delta)

RULE_VERSION = "v1"
THREAT_GAIN_THRESHOLD = 0.1  # Configurable trigger tuned on the seed-7 fixture; not a universal threshold.
TRANSITION_WINDOW_MS = 12_000
TRANSITION_MIN_PROGRESS_M = 35.0
PRESS_DROP_RATIO = 0.6  # Later window PPDA at or below 60% of the previous valid window.
PRESS_COOLDOWN_MS = 10 * 60 * 1000
PRIORITY = {"goal": 3, "transition": 2, "chance": 2, "pressing_change": 2, "threat_gain": 1}

BASE_LIMITATIONS = [
    "Synthetic match data generated by a seeded simulator.",
    "Event locations only; no player tracking or off-ball positions are available.",
]


def _moment(run_id: str, match_id: str, rule: str, anchor: str, event: dict, source_sequence: int,
            evidence_ids: list[str], metrics: list[dict], facts: dict, limitations: list[str]) -> dict:
    return {
        "moment_id": f"{run_id}:{rule}:{RULE_VERSION}:{anchor}", "run_id": run_id, "match_id": match_id,
        "rule": rule, "rule_version": RULE_VERSION, "metric_version": METRIC_VERSION,
        "priority": PRIORITY[rule], "team_id": event.get("team_id"), "player_id": event.get("player_id"),
        "period": event["period"], "match_time_ms": event["match_time_ms"], "anchor_sequence": event["sequence"],
        "source_sequence": source_sequence, "evidence_ids": evidence_ids, "metrics": metrics, "facts": facts,
        "limitations": BASE_LIMITATIONS + limitations,
    }


def _metric(name: str, value: float, unit: str) -> dict:
    return {"name": name, "value": value, "unit": unit}


def detect_moments(events: list[dict], run_id: str, match_id: str, teams: list[str]) -> list[dict]:
    moments: list[dict] = []
    seen_possessions: set[str] = set()
    score = {team: 0 for team in teams}
    by_possession: dict[str, list[dict]] = {}
    open_transitions: list[dict] = []

    for event in events:
        possession = event.get("possession_id")
        if possession:
            by_possession.setdefault(possession, []).append(event)

        # Goal: validated goal event and resulting score.
        if event["type"] == "shot":
            chain = [e for e in by_possession.get(possession, []) if e["team_id"] == event["team_id"]][-6:]
            if event["is_goal"]:
                score[event["team_id"]] += 1
                moments.append(_moment(run_id, match_id, "goal", event["event_id"], event, event["sequence"],
                    [e["event_id"] for e in chain],
                    [_metric("shot_distance", shot_distance_m(event), "m"),
                     _metric("possession_actions", len(chain), "events")],
                    {"score": dict(score), "outcome": "goal"}, []))
            elif event["on_target"] and shot_distance_m(event) <= 18:
                moments.append(_moment(run_id, match_id, "chance", event["event_id"], event, event["sequence"],
                    [e["event_id"] for e in chain],
                    [_metric("shot_distance", shot_distance_m(event), "m")],
                    {"outcome": event["outcome"]},
                    ["Shot quality (xG) is not modelled; distance is reported instead."]))

        # Threat gain: one per possession, first completed pass at or above the trigger.
        delta = threat_delta(event)
        if delta and delta["delta"] >= THREAT_GAIN_THRESHOLD and possession not in seen_possessions:
            seen_possessions.add(possession)
            moments.append(_moment(run_id, match_id, "threat_gain", event["event_id"], event, event["sequence"],
                [event["event_id"]],
                [_metric("threat_delta", delta["delta"], "illustrative threat"),
                 _metric("forward_progress", forward_progress_m(event), "m"),
                 _metric("pass_distance", pass_distance_m(event), "m")],
                {**delta, "final_third_entry": final_third_entry(event), "box_entry": box_entry(event)},
                ["Illustrative threat grid; not calibrated and not a scoring probability."]))

        # Transition: a won turnover followed by rapid forward progress or a shot.
        if event["type"] in ("tackle", "interception") and event["outcome"] == "won":
            open_transitions.append({"turnover": event, "progress": 0.0, "chain": [event]})
        still_open = []
        for candidate in open_transitions:
            turnover = candidate["turnover"]
            if event is turnover:
                still_open.append(candidate)
                continue
            elapsed = event["match_time_ms"] - turnover["match_time_ms"]
            same_team = event.get("team_id") == turnover["team_id"]
            if event["period"] != turnover["period"] or elapsed > TRANSITION_WINDOW_MS or (event.get("team_id") and not same_team):
                continue
            if not same_team:
                still_open.append(candidate)
                continue
            candidate["chain"].append(event)
            if event["type"] == "pass" and event["outcome"] == "completed":
                candidate["progress"] += forward_progress_m(event)
            if candidate["progress"] >= TRANSITION_MIN_PROGRESS_M or event["type"] == "shot":
                moments.append(_moment(run_id, match_id, "transition", turnover["event_id"], turnover, event["sequence"],
                    [e["event_id"] for e in candidate["chain"]],
                    [_metric("forward_progress", round(candidate["progress"], 1), "m"),
                     _metric("elapsed", round(elapsed / 1000, 1), "s"),
                     _metric("actions", len(candidate["chain"]), "events")],
                    {"turnover_type": turnover["type"], "ended_in_shot": event["type"] == "shot"},
                    ["Sequence shows association with the turnover, not causation."]))
            elif event["type"] == "pass" and event["outcome"] == "completed":
                still_open.append(candidate)
        open_transitions = still_open

    moments.extend(_pressing_changes(events, run_id, match_id, teams))
    moments.sort(key=lambda moment: (moment["source_sequence"], -moment["priority"], moment["moment_id"]))
    return moments


def _pressing_changes(events: list[dict], run_id: str, match_id: str, teams: list[str]) -> list[dict]:
    moments = []
    series = ppda_series(events, teams)
    for team in teams:
        last_moment_ms = None
        for period in (1, 2):
            windows = [w for w in series if w["team_id"] == team and w["period"] == period and w["closed"]]
            previous = None
            for window in windows:
                if window["status"] != "ok":
                    continue  # Compare against the latest valid window in the same period only.
                if previous and window["value"] <= previous["value"] * PRESS_DROP_RATIO:
                    absolute = (period, window["start_ms"])
                    if last_moment_ms is None or absolute[0] != last_moment_ms[0] or window["start_ms"] - last_moment_ms[1] >= PRESS_COOLDOWN_MS:
                        last_moment_ms = absolute
                        closing = next((e for e in events if e["period"] == period and e["match_time_ms"] >= window["end_ms"]), None)
                        closing = closing or next(e for e in events if e["period"] == period and e["type"] == "period_end")
                        anchor_event = {"team_id": team, "player_id": None, "period": period,
                                        "match_time_ms": window["start_ms"], "sequence": closing["sequence"]}
                        anchor = f"p{period}-{window['start_ms'] // 60000:02d}-{window['end_ms'] // 60000:02d}"
                        moments.append(_moment(run_id, match_id, "pressing_change", anchor, anchor_event, closing["sequence"],
                            window["evidence_ids"],
                            [_metric("ppda", window["value"], "passes per defensive action"),
                             _metric("previous_ppda", previous["value"], "passes per defensive action"),
                             _metric("opponent_passes", window["opponent_passes"], "passes"),
                             _metric("defensive_actions", window["defensive_actions"], "actions")],
                            {"window": {k: window[k] for k in ("start_ms", "end_ms", "opponent_passes", "defensive_actions", "value")},
                             "previous_window": {k: previous[k] for k in ("start_ms", "end_ms", "opponent_passes", "defensive_actions", "value")},
                             "zone": window["zone"], "window_ms": PPDA_WINDOW_MS},
                            ["Lower PPDA describes defensive intensity; it does not prove pressing succeeded.",
                             "Consistent with increased pressure; not a confirmed tactical change."]))
                previous = window
    return moments
